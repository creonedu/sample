  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  // 일기 내용에 맞는 주제를 점수순으로 돌려줍니다.
  function rankThemes(text) {
    const t = ' ' + String(text || '') + ' ';
    const scored = themes.map((th) => {
      let score = 0;
      for (const k of th.keywords) if (t.includes(k)) score += k.length > 1 ? 2 : 1;
      return { th, score };
    }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score);
    const out = scored.map((x) => x.th);
    for (const id of ['thanks', 'daily']) {
      const th = themes.find((x) => x.id === id);
      if (!out.includes(th)) out.push(th);
    }
    return out;
  }

  // 추천 말씀 count 구절. exclude 에 있는 구절(ref)은 건너뜁니다 — '다른 말씀 보기'용.
  function recommend(text, count, exclude) {
    const ex = new Set(exclude || []);
    const ranked = rankThemes(text);
    const picks = [];
    const used = new Set();
    // 상위 주제부터 한 구절씩 돌아가며 뽑아 다양하게 섞습니다.
    const pools = ranked.map((th) => shuffle(th.verses).map((v) => ({ ...v, theme: th.name })));
    let round = 0;
    while (picks.length < count && round < 10) {
      for (const pool of pools) {
        const v = pool.find((x) => !used.has(x.ref) && !ex.has(x.ref));
        if (v) { used.add(v.ref); picks.push(v); }
        if (picks.length >= count) break;
      }
      round++;
    }
    // 모두 보여 줬다면 처음부터 다시
    if (picks.length < count && ex.size) return recommend(text, count, []);
    return picks;
  }

